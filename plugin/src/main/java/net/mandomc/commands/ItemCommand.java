package net.mandomc.commands;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Objects;
import net.kyori.adventure.text.Component;
import net.kyori.adventure.text.format.TextDecoration;
import net.kyori.adventure.text.minimessage.MiniMessage;
import net.kyori.adventure.text.minimessage.tag.resolver.Placeholder;
import net.mandomc.gameplay.items.ItemBrowser;
import net.mandomc.gameplay.items.ItemCatalog;
import org.bukkit.Bukkit;
import org.bukkit.command.CommandSender;
import org.bukkit.configuration.file.YamlConfiguration;
import org.bukkit.entity.Player;
import org.bukkit.inventory.ItemStack;
import org.bukkit.plugin.java.JavaPlugin;

/** Item administration and delivery; vendor items are generated by their own provider. */
public final class ItemCommand implements ItemBrowser.Feedback {
    private final JavaPlugin plugin;
    private final ItemCatalog catalog;
    private final YamlConfiguration language;
    private final ItemBrowser browser;

    public ItemCommand(JavaPlugin plugin, ItemCatalog catalog, YamlConfiguration language, RootCommand root) {
        this.plugin = plugin;
        this.catalog = catalog;
        this.language = language;
        browser = new ItemBrowser(plugin, catalog, this);
        root.register("give", "mandomc.items.give", this::giveCommand, this::completeGive);
        root.register("items", "mandomc.items.reload", this::reloadCommand,
                (sender, args) -> args.length == 1 && "reload".startsWith(args[0].toLowerCase(Locale.ROOT))
                        ? List.of("reload") : List.of());
    }

    private void giveCommand(CommandSender sender, String[] args) {
        if (args.length == 0) {
            if (sender instanceof Player player) browser.open(player, player);
            else message(sender, "player-required", "", "");
        } else if (args.length == 1) {
            String id = args[0].toLowerCase(Locale.ROOT);
            if (catalog.ids().contains(id)) {
                if (sender instanceof Player player) grant(sender, player, id, false);
                else message(sender, "player-required", "", "");
            } else {
                Player target = Bukkit.getPlayerExact(args[0]);
                if (target == null) message(sender, "unknown-player-item", args[0], "");
                else if (sender instanceof Player player) browser.open(player, target);
                else message(sender, "console-item-required", "", "");
            }
        } else if (args.length == 2) {
            Player target = Bukkit.getPlayerExact(args[0]);
            if (target == null) message(sender, "player-required", "", "");
            else grant(sender, target, args[1].toLowerCase(Locale.ROOT), false);
        } else message(sender, "usage", "", "");
    }

    private void reloadCommand(CommandSender sender, String[] args) {
        if (args.length != 1 || !args[0].equalsIgnoreCase("reload")) {
            message(sender, "usage-reload", "", "");
            return;
        }
        try {
            catalog.reload();
            browser.close();
            message(sender, "reloaded", Integer.toString(catalog.ids().size()), "");
        } catch (Exception error) {
            plugin.getLogger().warning("Item reload rejected; previous catalog kept: " + error.getMessage());
            message(sender, "reload-failed", "", "");
        }
    }

    @Override
    public void give(Player sender, Player target, String id, boolean stack) {
        grant(sender, target, id, stack);
    }

    private void grant(CommandSender sender, Player target, String id, boolean stack) {
        if (!sender.hasPermission("mandomc.items.give")) {
            message(sender, "denied", "", "");
            return;
        }
        if (!target.isOnline()) {
            message(sender, "player-required", "", "");
            return;
        }
        ItemStack item;
        try {
            item = catalog.create(id);
        } catch (RuntimeException error) {
            plugin.getLogger().warning("Cannot give " + id + ": " + error.getMessage());
            message(sender, "unavailable", id, "");
            return;
        }
        if (item == null) {
            message(sender, "unknown", id, "");
            return;
        }
        int amount = stack ? item.getMaxStackSize() : 1;
        int capacity = 0;
        for (var slot : target.getInventory().getStorageContents()) {
            int limit = Math.min(item.getMaxStackSize(), target.getInventory().getMaxStackSize());
            if (slot == null || slot.getType().isAir()) capacity += limit;
            else if (slot.isSimilar(item)) capacity += Math.max(0, limit - slot.getAmount());
        }
        if (capacity < amount) {
            message(sender, "full", "", target.getName());
            return;
        }
        item.setAmount(amount);
        target.getInventory().addItem(item);
        message(sender, "given", amount + " × " + id, target.getName());
    }

    @Override
    public Component text(String key, String value, String player) {
        return MiniMessage.miniMessage().deserialize(Objects.requireNonNull(language.getString("items." + key)),
                Placeholder.unparsed("value", value), Placeholder.unparsed("player", player))
                .decoration(TextDecoration.ITALIC, false);
    }

    private void message(CommandSender sender, String key, String value, String player) {
        sender.sendMessage(text(key, value, player));
    }

    private List<String> completeGive(CommandSender sender, String[] args) {
        var options = new ArrayList<String>();
        if (args.length == 1) {
            options.addAll(catalog.ids());
            Bukkit.getOnlinePlayers().stream().map(Player::getName).forEach(options::add);
        } else if (args.length == 2 && Bukkit.getPlayerExact(args[0]) != null) options.addAll(catalog.ids());
        String prefix = args.length == 0 ? "" : args[args.length - 1].toLowerCase(Locale.ROOT);
        return options.stream().filter(s -> s.toLowerCase(Locale.ROOT).startsWith(prefix)).distinct().sorted().toList();
    }

    public void close() { browser.close(); }
}
